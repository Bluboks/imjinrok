#!/usr/bin/env node
import { buildUiRuntimeTracePlan } from "./extract-ui-runtime-trace-plan.mjs";

const DEFAULT_EXECUTABLE_PATH = "original/imjinrok2/imjinrok2.exe";
const VALID_MODES = new Set(["setup", "capture-file"]);

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = parseArgs(process.argv.slice(2));
  const script = generateUiX64dbgScript(args.input ?? DEFAULT_EXECUTABLE_PATH, {
    mode: args.mode ?? "setup",
    capturePrefix: args.capturePrefix,
    category: args.category,
  });
  process.stdout.write(script);
}

export function generateUiX64dbgScript(executablePath = DEFAULT_EXECUTABLE_PATH, options = {}) {
  const mode = options.mode ?? "setup";
  if (!VALID_MODES.has(mode)) {
    throw new Error(`Invalid mode: ${mode}`);
  }

  const category = options.category ?? "all";
  const capturePrefix = sanitizeFilename(options.capturePrefix ?? "codex-imjinrok-ui-trace");
  const plan = buildUiRuntimeTracePlan(executablePath);
  const breakpoints = dedupeBreakpoints(plan.breakpoints)
    .filter((breakpoint) => category === "all" || breakpoint.category === category)
    .sort((left, right) => Number.parseInt(left.address, 16) - Number.parseInt(right.address, 16));

  if (breakpoints.length === 0) {
    throw new Error(`No UI trace breakpoints matched category: ${category}`);
  }

  const lines = [
    "// Generated by tools/imjinrok/generate-ui-x64dbg-script.mjs",
    "// Execute after imjinrok2.exe is loaded. This sets UI logging breakpoints; it is not runtime proof by itself.",
    `log "IMJINROK_UI_TRACE_SETUP sha=${plan.executableSha256} mode=${mode} category=${sanitizeLogValue(category)}"`,
  ];

  for (const breakpoint of breakpoints) {
    lines.push(...breakpointLines(breakpoint, { capturePrefix, mode }));
  }

  lines.push('log "IMJINROK_UI_TRACE_READY"', "ret");

  return `${lines.join("\n")}\n`;
}

function dedupeBreakpoints(breakpoints) {
  const seen = new Set();
  const deduped = [];

  for (const breakpoint of breakpoints) {
    if (!breakpoint.address || seen.has(breakpoint.address)) {
      continue;
    }
    seen.add(breakpoint.address);
    deduped.push(breakpoint);
  }

  return deduped;
}

function breakpointLines(breakpoint, options = {}) {
  const mode = options.mode ?? "setup";
  const capturePrefix = options.capturePrefix ?? "codex-imjinrok-ui-trace";
  const id = sanitizeLogValue(breakpoint.id ?? breakpoint.address);
  const probeId = sanitizeLogValue(breakpoint.probeId ?? "unknown");
  const category = sanitizeLogValue(breakpoint.category ?? "unknown");
  const role = sanitizeLogValue(breakpoint.role ?? "unknown");
  const callTarget = sanitizeLogValue(breakpoint.callTarget ?? "unknown");
  const filenameId = sanitizeFilename(id);
  const filenameAddress = sanitizeFilename(breakpoint.address);
  const staticStrings = sanitizeLogValue((breakpoint.staticContext?.pushedStrings ?? []).join("|"));
  const staticFields = sanitizeLogValue((breakpoint.staticContext?.fieldOffsets ?? []).join("|"));
  const logFormat = [
    "IMJINROK_UI_TRACE",
    `id=${id}`,
    `probe=${probeId}`,
    `category=${category}`,
    `role=${role}`,
    `target=${callTarget}`,
    `strings=${staticStrings}`,
    `fields=${staticFields}`,
    "cip={p:cip}",
    "eax={p:eax}",
    "ebx={p:ebx}",
    "ecx={p:ecx}",
    "edx={p:edx}",
    "esi={p:esi}",
    "edi={p:edi}",
    "ebp={p:ebp}",
    "esp={p:esp}",
    "stack0={p:dword:[esp]}",
    "stack1={p:dword:[esp+4]}",
    "stack2={p:dword:[esp+8]}",
    "stack3={p:dword:[esp+c]}",
    "stack4={p:dword:[esp+10]}",
    "stack5={p:dword:[esp+14]}",
    "stack6={p:dword:[esp+18]}",
    "stack7={p:dword:[esp+1c]}",
    "stack8={p:dword:[esp+20]}",
    "stack9={p:dword:[esp+24]}",
    "stack10={p:dword:[esp+28]}",
    "stack11={p:dword:[esp+2c]}",
  ].join(" ");

  const lines = [
    `scriptcmd bp ${breakpoint.address}`,
    `scriptcmd SetBreakpointSilent ${breakpoint.address}, 1`,
    `scriptcmd SetBreakpointLog ${breakpoint.address}, "${logFormat}"`,
    `scriptcmd SetBreakpointCondition ${breakpoint.address}, 0`,
  ];

  if (mode === "capture-file") {
    const stackPath = `C:\\rev\\logs\\${capturePrefix}-${filenameId}-${filenameAddress}-stack.bin`;
    lines.push(
      `scriptcmd SetBreakpointCommand ${breakpoint.address}, "savedata ${stackPath}, esp, 0x80"`,
      `scriptcmd SetBreakpointCommandCondition ${breakpoint.address}, 1`,
      `scriptcmd SetBreakpointFastResume ${breakpoint.address}, 0`,
    );
  }

  return lines;
}

function sanitizeLogValue(value) {
  return String(value)
    .replaceAll("\\", "/")
    .replaceAll(/\s+/g, "_")
    .replaceAll('"', "'");
}

function sanitizeFilename(value) {
  return String(value).replaceAll(/[^A-Za-z0-9_.-]+/g, "_").replaceAll(/^_+|_+$/g, "");
}

function parseArgs(argv) {
  const parsed = {};

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--input") {
      parsed.input = argv[index + 1];
      index += 1;
      continue;
    }
    if (arg === "--mode") {
      parsed.mode = argv[index + 1];
      index += 1;
      continue;
    }
    if (arg === "--capture-prefix") {
      parsed.capturePrefix = argv[index + 1];
      index += 1;
      continue;
    }
    if (arg === "--category") {
      parsed.category = argv[index + 1];
      index += 1;
      continue;
    }
    throw new Error(`Unknown argument: ${arg}`);
  }

  return parsed;
}
