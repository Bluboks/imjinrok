#!/usr/bin/env node
import { buildCampaignRuntimeTracePlan } from "./extract-campaign-runtime-trace-plan.mjs";

const DEFAULT_EXECUTABLE_PATH = "original/imjinrok2/imjinrok2.exe";
const DEFAULT_MISSION_SCOPE = "K01";
const VALID_MODES = new Set(["setup", "capture-file", "headless-run", "headless-init-smoke"]);
const VM_TARGET_EXECUTABLE = "C:\\rev\\work\\imjinrok2-ascii\\imjinrok2.exe";
const VM_TARGET_WORKING_DIRECTORY = "C:\\rev\\work\\imjinrok2-ascii";
const WATCHED_GLOBALS = [
  ["g_7c5f80", "0x007c5f80"],
  ["g_8438dc", "0x008438dc"],
  ["g_8438de", "0x008438de"],
  ["g_8438e2", "0x008438e2"],
  ["g_8438e4", "0x008438e4"],
  ["g_8438e6", "0x008438e6"],
  ["g_8438e8", "0x008438e8"],
  ["g_882e04", "0x00882e04"],
];

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = parseArgs(process.argv.slice(2));
  const script = generateCampaignX64dbgScript(args.input ?? DEFAULT_EXECUTABLE_PATH, {
    mode: args.mode ?? "setup",
    capturePrefix: args.capturePrefix,
    mission: args.mission ?? DEFAULT_MISSION_SCOPE,
  });
  process.stdout.write(script);
}

export function generateCampaignX64dbgScript(executablePath = DEFAULT_EXECUTABLE_PATH, options = {}) {
  const mode = options.mode ?? "setup";
  if (!VALID_MODES.has(mode)) {
    throw new Error(`Invalid mode: ${mode}`);
  }
  const mission = options.mission ?? DEFAULT_MISSION_SCOPE;
  const capturePrefix = sanitizeFilename(options.capturePrefix ?? "codex-imjinrok-campaign-trace");

  const plan = buildCampaignRuntimeTracePlan(executablePath, { mission });
  const breakpoints = dedupeBreakpoints(plan.breakpoints)
    .filter((breakpoint) => breakpoint.address)
    .sort((left, right) => Number.parseInt(left.address, 16) - Number.parseInt(right.address, 16));

  const lines = [
    "// Generated by tools/imjinrok/generate-campaign-x64dbg-script.mjs",
    "// Execute after imjinrok2.exe is loaded. This sets logging breakpoints; it is not runtime proof by itself.",
    `log "IMJINROK_TRACE_SETUP sha=${plan.executableSha256} mode=${mode} mission=${plan.scope.mission}"`,
  ];

  if (mode === "headless-run" || mode === "headless-init-smoke") {
    lines.push(
      `scriptcmd init "${VM_TARGET_EXECUTABLE}", "", "${VM_TARGET_WORKING_DIRECTORY}"`,
      'log "IMJINROK_TRACE_INIT_LOADED pid={p:$pid}"',
    );
  }

  if (mode === "headless-init-smoke") {
    lines.push("scriptcmd stop", 'log "IMJINROK_TRACE_INIT_STOPPED"', "ret");
    return `${lines.join("\n")}\n`;
  }

  for (const breakpoint of breakpoints) {
    lines.push(...breakpointLines(breakpoint, { capturePrefix, mode, watchedGlobals: plan.watchedGlobals }));
  }

  if (mode === "headless-run") {
    lines.push(
      'log "IMJINROK_TRACE_RUNNING"',
      "scriptcmd erun",
      "// Keep the headless debugger alive for external QGA input and marker cleanup.",
      "pause",
    );
  } else {
    lines.push('log "IMJINROK_TRACE_READY"', "ret");
  }

  return `${lines.join("\n")}\n`;
}

function dedupeBreakpoints(breakpoints) {
  const seen = new Set();
  const deduped = [];

  for (const breakpoint of breakpoints) {
    if (!breakpoint.address || seen.has(breakpoint.address)) {
      continue;
    }
    seen.add(breakpoint.address);
    deduped.push(breakpoint);
  }

  return deduped;
}

function breakpointLines(breakpoint, options = {}) {
  const mode = options.mode ?? "setup";
  const capturePrefix = options.capturePrefix ?? "codex-imjinrok-campaign-trace";
  const watchedGlobals = options.watchedGlobals ?? WATCHED_GLOBALS.map(([name, address]) => ({
    name,
    address,
  }));
  const id = sanitizeLogValue(breakpoint.id ?? breakpoint.role ?? breakpoint.address);
  const filenameId = sanitizeFilename(id);
  const filenameAddress = sanitizeFilename(breakpoint.address);
  const mission = sanitizeLogValue(breakpoint.mission ?? "unknown");
  const role = sanitizeLogValue(breakpoint.role ?? "unknown");
  const script = sanitizeLogValue(breakpoint.sourceScript ?? "");
  const logFormat = [
    "IMJINROK_TRACE",
    `id=${id}`,
    `mission=${mission}`,
    `role=${role}`,
    `script=${script}`,
    "cip={p:cip}",
    "eax={p:eax}",
    "ebx={p:ebx}",
    "ecx={p:ecx}",
    "edx={p:edx}",
    "esi={p:esi}",
    "edi={p:edi}",
    "ebp={p:ebp}",
    "esp={p:esp}",
    "stack0={p:dword:[esp]}",
    "stack1={p:dword:[esp+4]}",
    "stack2={p:dword:[esp+8]}",
    "stack3={p:dword:[esp+c]}",
    ...watchedGlobals.map((global) => `${watchedGlobalName(global)}={p:dword:[${global.address}]}`),
  ].join(" ");

  const lines = [
    `scriptcmd bp ${breakpoint.address}`,
    `scriptcmd SetBreakpointSilent ${breakpoint.address}, 1`,
    `scriptcmd SetBreakpointLog ${breakpoint.address}, "${logFormat}"`,
    `scriptcmd SetBreakpointCondition ${breakpoint.address}, 0`,
  ];

  if (mode === "capture-file") {
    const stackPath = `C:\\rev\\logs\\${capturePrefix}-${filenameId}-${filenameAddress}-stack.bin`;
    lines.push(
      `scriptcmd SetBreakpointCommand ${breakpoint.address}, "savedata ${stackPath}, esp, 0x40"`,
      `scriptcmd SetBreakpointCommandCondition ${breakpoint.address}, 1`,
      `scriptcmd SetBreakpointFastResume ${breakpoint.address}, 0`,
    );
  }

  return lines;
}

function watchedGlobalName(global) {
  return global.name ?? `g_${global.address.replace(/^0x0*/i, "").toLowerCase()}`;
}

function sanitizeLogValue(value) {
  return String(value).replaceAll("\\", "/").replaceAll(/\s+/g, "_").replaceAll('"', "'");
}

function sanitizeFilename(value) {
  return String(value).replaceAll(/[^A-Za-z0-9_.-]+/g, "_").replaceAll(/^_+|_+$/g, "");
}

function parseArgs(argv) {
  const parsed = {};

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--input") {
      parsed.input = argv[index + 1];
      index += 1;
      continue;
    }
    if (arg === "--mode") {
      parsed.mode = argv[index + 1];
      index += 1;
      continue;
    }
    if (arg === "--capture-prefix") {
      parsed.capturePrefix = argv[index + 1];
      index += 1;
      continue;
    }
    if (arg === "--mission") {
      parsed.mission = argv[index + 1];
      index += 1;
      continue;
    }
    throw new Error(`Unknown argument: ${arg}`);
  }

  return parsed;
}
